def same_driver(x,y,px,py):
    assert x==y, ('driver connections/name/type changed',x['name'],y['name'])
    assert px==py, ('driver initialization/function changed',x['name'])


def parameter_reader(modules):
    """Same exact parameters, parsed once per module instead of per cell."""
    @lru_cache(None)
    def children(kind):
        rows=[(name.lstrip('\\'),child) for child,name,_ in CELL.findall(modules[kind])]
        assert len(rows)==len(dict(rows)), 'duplicate hierarchy instance'
        return dict(rows)
    @lru_cache(None)
    def kind_at(hierarchy):
        if not hierarchy:return 'g2_top'
        parent,_,local=hierarchy.rpartition('/')
        return children(kind_at(parent))[local]
    @lru_cache(None)
    def table(kind):
        result={}
        for name,key,value in PARAM.findall(modules[kind]):
            local=name.strip().lstrip('\\');row=result.setdefault(local,{})
            assert key not in row, 'duplicate primitive parameter'
            row[key]=value.strip()
        return result
    def get(cell):
        parent,_,local=cell['name'].rpartition('/')
        return table(kind_at(parent)).get(local,{})
    return get


def effective_zero_init(overrides,defaults):
    expected={f'INIT_RAM_{i:02X}' for i in range(64)}
    assert set(defaults)==expected and all(v==0 for v in defaults.values()), 'SDPB vendor defaults differ'
    assert set(overrides)<=expected
    effective=dict(defaults)
    for name,value in overrides.items():
        m=re.fullmatch(r"256'h([0-9a-fA-F]+)",value);assert m,('unsupported SDPB INIT',name,value)
        effective[name]=int(m[1],16)
    assert all(v==0 for v in effective.values()), 'new block store has a nonzero initial value'
    return dict(explicit_zero_parameters=len(overrides),vendor_default_zero_parameters=64-len(overrides),effective_zero_parameters=64)


def review(source,baseline):
    source,baseline=Path(source).resolve(),Path(baseline).resolve()
    manifest=json.loads((source/'manifest.json').read_text())
    job=json.loads((source/'job.json').read_text())
    original=Path(manifest['frozen_source_build']).resolve()
    assert baseline.name=='sfp_lane2_observation_lw_pnr15'
    report=(baseline/'impl/pnr/g2_top.rpt.txt').read_text()
    assert re.search(r'PR0004\).*total 184 unrouted nets',report)
    assert re.search(r'BSRAM\s+\|\s+326/340',report)
    assert (baseline/'g2_top.vg').read_bytes()==(original/'impl/gwsynthesis/g2_top.vg').read_bytes()
    assert job['phase']=='synthesis_complete' and job['tool_exit']==0
    for flag in ('small_block_stores','snapshot_private_reset','slf_point_planes',
                 'slf_row_banks','observation_reuse_prefetch','bank_select_data_fanout',
                 'real_sfp','full_control_telemetry'):
        assert manifest[flag],flag
    assert not manifest['control_weights_changed'] and manifest['clock_core_mhz']==50
    old_manifest=json.loads((original/'manifest.json').read_text())
    old_files={Path(n).relative_to(original).as_posix() for n in old_manifest['source_files']}
    new_files={Path(n).relative_to(source).as_posix() for n in manifest['source_files']}
    assert old_files==new_files and len(new_files)==68, 'full input set changed'
    changed=sorted(n for n in new_files if (source/n).read_bytes()!=(original/n).read_bytes())
    assert manifest['small_block_stores_selected'], 'the broad SYN15 candidate exceeded the RAM budget'
    host='nav/rtl/net/host_mbx.v'
    assert changed==sorted(job['modified_rtl_inputs'])==[RAM,host]
    assert (source/RAM).read_text()==transform_selected((original/RAM).read_text())
    assert (source/host).read_text()==select_mailboxes((original/host).read_text())
    probe=json.loads(Path(manifest['small_block_stores_probe']).read_text())
    assert Path(probe['source']).resolve()==original and probe['passed']
    assert [c['variant'] for c in probe['checks']]==['rtl','mapped','physical_mapped']
    assert all('TEST PASSED checks=90122' in c['result'] for c in probe['checks'])
    normalized=(source/RAM).read_text().replace(',parameter integer BLOCK_MAILBOX=0','').replace('BLOCK_MAILBOX && ','')
    assert (Path(probe['build'])/'physical/ram.v').read_text()==normalized
    selected=json.loads(Path(manifest['small_block_stores_selection_probe']).read_text())
    assert selected['passed'] and Path(selected['source']).resolve()==original
    assert selected['enabled_memory_bodies_match_prior_physical_proof']
    assert 'TEST PASSED checks=90122' in selected['checks'][0]['result']
    def assets(root):
        return {p.relative_to(root):p for p in root.rglob('*') if p.is_file()
                and p.suffix.lower() in ('.hex','.mem','.bin','.mif') and 'impl' not in p.relative_to(root).parts}
    a,b=assets(original),assets(source)
    assert a.keys()==b.keys() and len(a)==104
    assert all(p.read_bytes()==b[n].read_bytes() for n,p in a.items())
    for name in ('g2.cst','g2.sdc','ip/serdes.csr'):
        assert (source/name).read_bytes()==(original/name).read_bytes(),name
    assert (source/'ip/serdes.csr').read_bytes()==(baseline/'ip/serdes.csr').read_bytes()
    old=json.loads((original/'memory_inventory.json').read_text())
    new=json.loads((source/'memory_inventory.json').read_text())
    key=lambda inv:{r['path']:(r['primitive'],r['parameters']) for r in inv['leaves']}
    a,b=key(old),key(new)
    assert len(a)==316 and all(b.get(n)==v for n,v in a.items()), 'original BSRAM geometry changed'
    additions=[r for r in new['leaves'] if r['path'] not in a]
    assert len(additions)==4, ('new memory leaf count',len(additions))
    assert new['expanded_bsram_count']==320 and new['wide32_36_count']==13
    assert new['predicted_split_bsram']==333<=336
    assert new['primitive_types']['GTR12_QUAD']==1
    old_vg=original/'impl/gwsynthesis/g2_top.vg';new_vg=source/'impl/gwsynthesis/g2_top.vg'
    before,after=read(old_vg),read(new_vg)
    old_defs,new_defs=definitions(old_vg),definitions(new_vg)
    old_params,new_params=parameter_reader(old_defs),parameter_reader(new_defs)
    directions=primitive_directions(LIBRARY)
    default_store_checks=[]
    for prefix in ('u_nav/u_match/u_cand/','u_nav/u_match/u_res/'):
        x={n:c for n,c in before.items() if n.startswith(prefix)}
        y={n:c for n,c in after.items() if n.startswith(prefix)}
        assert x==y and x,('unselected table implementation changed',prefix)
        assert all(old_params(c)==new_params(y[n]) for n,c in x.items())
        default_store_checks.append(dict(prefix=prefix,cells=len(x),
            distributed_RAM16=sum(c['kind']=='RAM16SDP4' for c in x.values()),all_connections_and_INIT_identical=True))
    # The inventory intentionally omits INIT arrays; check these separately.
    old_ram_names={r['path'].removeprefix('g2_top/').replace('\\','') for r in old['leaves']}
    assert len(old_ram_names)==316
    for name in old_ram_names:
        assert old_params(before[name])==new_params(after[name]),('original RAM INIT changed',name)
    added_cells=[after[r['path'].removeprefix('g2_top/').replace('\\','')] for r in additions]
    primitive=re.search(r'\bmodule\s+SDPB\b(.*?)\bendmodule\b',LIBRARY.read_text(),re.S)[1]
    pairs=re.findall(r"parameter\s+(INIT_RAM_[0-9A-F]{2})\s*=\s*256'h([0-9a-fA-F]+)\s*;",primitive)
    assert len(pairs)==64
    defaults={k:int(v,16) for k,v in pairs}
    try:effective_zero_init({'INIT_RAM_00':"256'h1"},defaults)
    except AssertionError:nonzero_init_rejected=True
    else:raise AssertionError('nonzero initial word accepted')
    init_checks=[]
    for prefix in TARGETS:
        cell,=[c for c in added_cells if c['name'].startswith(prefix)]
        assert cell['kind']=='SDPB'
        assert cell['ports']['CLKA']==cell['ports']['CLKB']==['clk50_d']
        assert cell['ports']['RESET']==['GND']
        p=new_params(cell);assert p==parameters(cell,new_defs), 'cached parameter parser differs'
        width=1 if '/u_bm/' in prefix else 32
        assert p['BIT_WIDTH_0']==p['BIT_WIDTH_1']==str(width)
        assert p['READ_MODE']=="1'b0"
        init={k:v for k,v in p.items() if k.startswith('INIT_RAM_')}
        initialization=effective_zero_init(init,defaults)
        assert not any(c['kind']=='RAM16SDP4' and n.startswith(prefix) for n,c in after.items())
        init_checks.append(dict(name=cell['name'],width=width,clock='clk50_d',**initialization))
    plan=json.loads((ROOT/'integration/g2/clock_resource_plan_lane2_observation_lw.json').read_text())
    names=[r['net'] for r in plan['promote']+plan['prefer_global']]+plan['local']
    assert len(names)==len(set(names))==14
    cst=(baseline/'g2.cst').read_text()
    assert re.findall(r'^CLOCK_LOC "([^"]+)"',cst,re.M)==names
    a,b=driver_index(before,directions),driver_index(after,directions)
    route=[]
    for net in names+['clk50_d','rgmii_rxc_d','h_rx_clk','h_tx_clk']:
        assert len(a.get(net,[]))==len(b.get(net,[]))==1,('driver missing/nonunique',net)
        x,y=a[net][0],b[net][0];px,py=old_params(x),new_params(y)
        same_driver(x,y,px,py)
        route.append(dict(net=net,driver=y['name'],kind=y['kind'],parameters_identical=True))
    # Three targeted negative checks protect the name/connection/INIT boundary.
    x=a[names[0]][0];p=old_params(x);assert p==parameters(x,old_defs);rejected=[]
    for mutation in ('input','driver','INIT'):
        y=copy.deepcopy(x);q=dict(p)
        if mutation=='input':
            pin=next(k for k in y['ports'] if directions[y['kind']][k]=='input')
            y['ports'][pin]=['VCC' if y['ports'][pin]!=['VCC'] else 'GND']
        elif mutation=='driver':y['name']+='__wrong'
        else:q['INIT']="16'h0" if q.get('INIT')!="16'h0" else "16'h1"
        try:same_driver(x,y,p,q)
        except AssertionError:rejected.append(mutation)
        else:raise AssertionError(('invalid driver accepted',mutation))
    lane=verify_frozen(source,original,manifest['sfp_lane2_from_build'])
    lane['actual_synthesized_clock_pins']=verify_synthesized_clock_pins(after)
    reference=json.loads((baseline/'cdc_reference_audit.json').read_text())
    lidar=revalidate(before,after,reference,directions,old_defs,new_defs)
    sfp=audit_sfp(new_vg,True)
    assert sfp['passed'] and len(sfp['paths'])==51
    assert json.loads(json.dumps(sfp['paths']))==json.loads((baseline/'sfp_cdc_reference.json').read_text())['paths']
    selectors=bank_load(after);assert selectors['maximum']<=128
    row='u_nav/u_match/u_ex/u_rb/'
    row_old={n:c for n,c in before.items() if n.startswith(row)}
    row_new={n:c for n,c in after.items() if n.startswith(row)}
    assert row_old==row_new and sum(c['kind']=='RAM16SDP4' for c in row_new.values())==250
    # Preserve 77 hold-only / 77 maximum-delay constraints without adding any.
    sdc=(baseline/'g2.sdc').read_text()
    assert len(re.findall(r'^set_false_path\b.*-hold',sdc,re.M))==77
    assert len(re.findall(r'^set_max_delay\b',sdc,re.M))==77
    assert sorted(float(v) for v in re.findall(r'^create_clock\b.*?-period\s+(\S+)',sdc,re.M))==[8,8,10,20]
    summary=json.loads((source/'synthesis_summary.json').read_text())
    prior=json.loads((original/'synthesis_summary.json').read_text())
    assert not summary['errors'] and summary['actual_synthesis_global_freq_mhz']==50
    val=lambda s,k:int(s['synthesis_hierarchy'][0].get(k,'0').split('(')[0])
    delta={k:val(summary,k)-val(prior,k) for k in ('T_Lut','T_Register','T_Alu','T_Ssram','T_Bsram','T_MULTALU27X18')}
    assert delta['T_Lut']<0 and delta['T_Register']<=0 and delta['T_MULTALU27X18']==0
    dsp_fields=('T_MULTALU27X18','T_MULT12X12','T_MULT27X36','T_MULTADDALU12X12')
    assert all(val(summary,k)==val(prior,k) for k in dsp_fields)
    return dict(passed=True,source=str(source),baseline=str(baseline),original=str(original),
        modified_rtl_inputs=changed,unchanged_inputs=len(new_files)-2,unchanged_assets=104,
        original_RAMs_and_parameters_and_INIT_preserved=316,new_RAMs=init_checks,
        vendor_SDPB_defaults_file=str(LIBRARY),nonzero_initialization_mutation_rejected=nonzero_init_rejected,
        source_bsram=320,wide_leaves=13,predicted_physical_bsram=333,physical_is_prediction=True,
        resource_delta=delta,module_proof=probe['checks'],selection_proof=selected,driver_checks=route,strict_targets=14,
        unselected_candidate_and_result_store_checks=default_store_checks,
        true_clocks=4,unproved_aliases=0,negative_driver_checks_rejected=rejected,
        lidar26=lidar,host51=sfp,lane2=lane,bank_selector_max_load=selectors['maximum'],
        row_RAM16_preserved=250,clock_periods_ns=[20,10,8,8],hold_only=77,max_delay=77,
        original_DSP_resources={k:val(summary,k) for k in dsp_fields},
        original_control_CPU_4500_weights_125Hz_and_stop_source_unchanged=True,
        no_DDR_in_candidate=True,failed_net_identities_unknown=True,deployment_accepted=False)

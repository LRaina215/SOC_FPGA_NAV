"""Generate fresh C-device DDR IP (includes vendor IP SYN), no G2 build/programming."""
import argparse
from datetime import datetime
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

IDE=Path('D:/Gowin2/Gowin_V1.9.12.04_x64/IDE')
OPTIONS={
    'User_Interface':'Controller','Memory_Type':'Components','Memory_Clock':400,
    'CLK_Ratio':'1:4','Dq_Width':32,'Dram_Width':16,'Ecc':'false',
    'Rank_Address':1,'Bank_Address':3,'Row_Address':15,'Column_Address':10,
    'SIM':'false','Burst_Mode':8,'Burst_Type':'SEQ','CAS_Latency':5,'CW_Latency':5,
    'Additive_Latency':0,'Wrire_Recovery':6,'Rtt_Nom':40,'Rtt_Wr':'OFF',
    'Addr_Cmd_Mode':'1T','OUTPUT_DRV':'LOW','User_Refresh':'false',
    'tRTP_Period':7500,'tRP_Period':12500,'tWTR_Period':7500,'tRC_Period':55000,
    'tRAS_Period':37500,'tRCD_Period':12500,'tFAW_Period':40000,'tRRD_Period':7500,
    'tCKE_Period':75000,'tREFI_Period':7800000,'tRFC_Period':160000,'tDLLK':512,
    'Debug_Parameter_Enable':'false','Debug_Port_Enable':'false',
    'MC_BSRAM':'true','MC_SSRAM':'false','MC_REG':'false','AXI4_Interface':'false'
}


def inspect(out):
    log=(out/'generate.log').read_text(errors='replace')
    options=dict(OPTIONS)
    if 'CONFIG.MC_SSRAM {true}' in log:
        options.update(MC_BSRAM='false',MC_SSRAM='true')
    for k,v in options.items():
        assert f'CONFIG.{k} {{{v}}}' in log, 'configuration readback '+k
    template=out/'ip/nav_ddr3_phy/nav_ddr3_phy_tmp.v'
    v=template.read_text(errors='replace')
    assert 'GW5AT-LV138PG484AC1/I0' in v and 'Device Version: C' in v,v[:600]
    assert template.with_name('nav_ddr3_phy.v').is_file()
    params=list(out.rglob('gwmc_param.v'));assert len(params)==1,params
    s=params[0].read_text()
    required={'DQ_WIDTH':'32','DRAM_WIDTH':'16','nCK_PER_CLK':'4','ROW_WIDTH':'15',
        'COL_WIDTH':'10','BANK_WIDTH':'3','RANK_WIDTH':'1','tCK':'2500'}
    for k,value in required.items():
        assert re.search(r'parameter\s+'+k+r'\s*=\s*'+value+r'\s*;',s),k
    xml=out/'ip/nav_ddr3_phy/temp/DDR3/nav_ddr3_phy_syn_rsc.xml'
    netlist=template.with_name('nav_ddr3_phy.vo').read_text(errors='replace')
    ram_names=set(re.findall(r'(?m)^(?:SDPB|SDPX9B|SP|SPX9|DPB|DPX9B|pROM|pROMX9)\s+(\\\S+|\S+)\s+\(',netlist))
    wide_names=set(re.findall(r'(?m)^defparam\s+(\\\S+|\S+)\s*\.BIT_WIDTH(?:_[01])?\s*=\s*(?:32|36)\s*;',netlist))
    assert len(ram_names)==int(ET.parse(xml).getroot().get('Bsram'))
    return dict(inspected_at=datetime.now().astimezone().isoformat(),generated=True,
        actual_parameters=str(params[0]),readback=required,vendor_ip_synthesis_observed=True,
        vendor_ip_synthesis_resources=ET.parse(xml).getroot().attrib,
        controller_buffer='SSRAM' if options['MC_SSRAM']=='true' else 'BSRAM',
        source_bsram_leaves=len(ram_names),wide32_36_leaves=len(ram_names&wide_names),
        predicted_physical_with_wide_split_1=len(ram_names)+len(ram_names&wide_names),
        physical_resources_verified=False,
        programmed=False,full_g2_synthesis_started=False)


def generate(out,mc_ssram=False):
    assert not out.exists()
    assert not mc_ssram, ('This installed C-device native-interface configurator did not retain MC_SSRAM '
        'in two readbacks. Do not repeat generation or count a requested mode as effective.')
    spec=ET.parse(IDE/'ipcore/DDR3/ddr3.ipspec').getroot()
    assert any(d.text=='GW5AT-138C-*' for d in spec.find('devices'))
    supported={x.get('tclcommand') for x in spec.find('options')}
    options=dict(OPTIONS)
    if mc_ssram:options.update(MC_BSRAM='false',MC_SSRAM='true')
    assert set(options)<=supported, set(options)-supported
    out.mkdir(parents=True)
    # SUG1220 4: DDR is generated by the IPFlow Tcl API, not ModGen.
    tcl=[f'create_project -name ddr3_candidate -dir {{{out.as_posix()}/project}} '
        '-pn GW5AT-LV138PG484AC1/I0 -device_version C',
        'create_ipc -name ddr3 -module_name Nav_DDR3_PHY -language Verilog '
        f'-file_name nav_ddr3_phy -dir {{{out.as_posix()}/ip}}']
    for k,v in options.items():
        if k in ('MC_BSRAM','MC_SSRAM','MC_REG'):continue
        tcl.append(f'set_property CONFIG.{k} {{{v}}} [get_ips Nav_DDR3_PHY]')
    # Radio choices are read back, rather than inferred from the request.
    selected='MC_SSRAM' if mc_ssram else 'MC_BSRAM'
    tcl.append(f'set_property CONFIG.{selected} {{true}} [get_ips Nav_DDR3_PHY]')
    tcl += ['report_property [get_ips Nav_DDR3_PHY]',
        'generate_target [get_ips Nav_DDR3_PHY]','exit']
    (out/'generate.tcl').write_text('\n'.join(tcl)+'\n')
    r=dict(started_at=datetime.now().astimezone().isoformat(),device='GW5AT-LV138PG484AC1/I0',
        device_version='C',requested=options,programmed=False,full_g2_synthesis_started=False,generated=False)
    try:
        with (out/'generate.log').open('w') as log:
            p=subprocess.run([str(IDE/'bin/gw_sh.exe'),str(out/'generate.tcl')],
                cwd=out,stdout=log,stderr=subprocess.STDOUT,timeout=120,
                creationflags=subprocess.CREATE_NO_WINDOW)
        r['tool_exit']=p.returncode
        assert p.returncode==0, 'see generate.log'
        readback=inspect(out)
        assert readback['controller_buffer']==('SSRAM' if mc_ssram else 'BSRAM'), 'MC buffer choice did not stick'
        r.update(readback)
    finally:
        r['ended_at']=datetime.now().astimezone().isoformat()
        (out/'generation_result.json').write_text(json.dumps(r,indent=2),encoding='utf-8')
    return r


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True)
    p.add_argument('--inspect',action='store_true');p.add_argument('--mc-ssram',action='store_true');a=p.parse_args()
    if a.inspect:
        result=inspect(a.out.resolve())
        (a.out/'inspection_result.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    else:result=generate(a.out.resolve(),a.mc_ssram)
    print(json.dumps(result,indent=2))
